import "server-only";

import * as React from "react";
import {
  Body,
  Button,
  Container,
  Head,
  Heading,
  Hr,
  Html,
  Img,
  Link,
  Markdown,
  Preview,
  Section,
  Text,
} from "@react-email/components";
import { render } from "@react-email/components";

import type { EmailDocumentDraft } from "@/lib/email-document";

type NewsletterBrand = {
  name: string;
  logo?: string | null;
  website?: string | null;
  primaryColor?: string | null;
};

function safeColor(value?: string | null) {
  return value && /^#[0-9a-f]{6}$/i.test(value) ? value : "#111827";
}

function NewsletterEmail({
  document,
  brand,
}: {
  document: EmailDocumentDraft;
  brand: NewsletterBrand;
}) {
  const primary = safeColor(brand.primaryColor);
  return (
    <Html lang="en">
      <Head />
      <Preview>{document.preheader || document.subject || brand.name}</Preview>
      <Body
        style={{
          backgroundColor: "#f3f4f6",
          color: "#111827",
          fontFamily:
            "Inter, -apple-system, BlinkMacSystemFont, 'Segoe UI', sans-serif",
          margin: 0,
          padding: "32px 12px",
        }}
      >
        <Container
          style={{
            backgroundColor: "#ffffff",
            border: "1px solid #e5e7eb",
            borderRadius: "16px",
            margin: "0 auto",
            maxWidth: "620px",
            padding: "40px 42px",
          }}
        >
          <Section style={{ marginBottom: "30px" }}>
            {brand.logo ? (
              <Img
                src={brand.logo}
                alt={brand.name}
                height="36"
                style={{
                  display: "block",
                  maxWidth: "160px",
                  objectFit: "contain",
                }}
              />
            ) : (
              <Text style={{ fontSize: "14px", fontWeight: 700, margin: 0 }}>
                {brand.name}
              </Text>
            )}
          </Section>

          {document.subject ? (
            <Heading
              as="h1"
              style={{
                color: "#111827",
                fontSize: "30px",
                letterSpacing: "-0.03em",
                lineHeight: 1.15,
                margin: "0 0 24px",
              }}
            >
              {document.subject}
            </Heading>
          ) : null}

          <Markdown
            markdownContainerStyles={{ color: "#1f2937" }}
            markdownCustomStyles={{
              h1: { fontSize: "28px", lineHeight: 1.2, margin: "28px 0 14px" },
              h2: { fontSize: "22px", lineHeight: 1.3, margin: "26px 0 12px" },
              h3: { fontSize: "18px", lineHeight: 1.35, margin: "22px 0 10px" },
              p: { fontSize: "16px", lineHeight: 1.65, margin: "0 0 18px" },
              li: { fontSize: "16px", lineHeight: 1.6, marginBottom: "8px" },
              link: { color: primary, textDecoration: "underline" },
              blockQuote: {
                borderLeft: `3px solid ${primary}`,
                color: "#4b5563",
                margin: "24px 0",
                paddingLeft: "18px",
              },
              image: { borderRadius: "12px", height: "auto", maxWidth: "100%" },
              hr: { borderColor: "#e5e7eb", margin: "28px 0" },
            }}
          >
            {document.bodyMarkdown ||
              "_Draft this issue in chat, then generate it here._"}
          </Markdown>

          {document.ctaLabel && document.ctaUrl ? (
            <Section style={{ margin: "30px 0" }}>
              <Button
                href={document.ctaUrl}
                style={{
                  backgroundColor: primary,
                  borderRadius: "9px",
                  color: "#ffffff",
                  display: "inline-block",
                  fontSize: "15px",
                  fontWeight: 700,
                  padding: "13px 20px",
                  textDecoration: "none",
                }}
              >
                {document.ctaLabel}
              </Button>
            </Section>
          ) : null}

          <Hr style={{ borderColor: "#e5e7eb", margin: "34px 0 20px" }} />
          <Text
            style={{
              color: "#6b7280",
              fontSize: "12px",
              lineHeight: 1.5,
              margin: 0,
            }}
          >
            {brand.website ? (
              <Link href={brand.website} style={{ color: "#6b7280" }}>
                {brand.name}
              </Link>
            ) : (
              brand.name
            )}
            {" · "}Preview generated by Wander Growth. Sending and unsubscribe
            behavior are configured in the product runtime.
          </Text>
        </Container>
      </Body>
    </Html>
  );
}

export async function renderNewsletterHtml(input: {
  document: EmailDocumentDraft;
  brand: NewsletterBrand;
}) {
  return render(<NewsletterEmail {...input} />);
}
